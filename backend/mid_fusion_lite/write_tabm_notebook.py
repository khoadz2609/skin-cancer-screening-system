        "# Evaluation Metric (pAUC)\n",
        "# ============================================\n",
        "def comp_score(y_true, y_pred, min_tpr=0.80):\n",
        "    y_true = np.asarray(y_true, dtype=np.float32)\n",
        "    y_pred = np.asarray(y_pred, dtype=np.float32)\n",
        "    v_gt = np.abs(y_true - 1.0)\n",
        "    v_pred = 1.0 - y_pred\n",
        "    max_fpr = abs(1.0 - min_tpr)\n",
        "    try:\n",
