        "# ============================================\n",
        "# Training & Mixup & Evaluation utilities\n",
        "# ============================================\n",
        "def mixup_data(X_num, X_cat, y, alpha=0.2):\n",
        "    if alpha > 0:\n",
        "        lam = np.random.beta(alpha, alpha)\n",
        "    else:\n",
        "        lam = 1.0\n",
        "\n",
        "    batch_size = X_num.size(0)\n",
        "    index = torch.randperm(batch_size).to(X_num.device)\n",
        "\n",
        "    mixed_X_num = lam * X_num + (1.0 - lam) * X_num[index, :]\n",
        "    \n",
        "    # Choose categorical features randomly between original and shuffled\n",
        "    mask = torch.rand(batch_size, X_cat.size(1)) < lam\n",
        "    mixed_X_cat = torch.where(mask.to(X_cat.device), X_cat, X_cat[index, :])\n",
        "    mixed_y = lam * y + (1.0 - lam) * y[index]\n",
        "    \n",
        "    return mixed_X_num, mixed_X_cat, mixed_y, lam\n",
        "\n",
        "def train_epoch(model, train_loader, optimizer, criterion, device, \n",
        "                gradient_clipping_norm=None, mixup_alpha=0.0, label_smoothing=0.0):\n",
        "    model.train()\n",
        "    total_loss = 0.0\n",
        "\n",
        "    for X_num, X_cat, y in train_loader:\n",
        "        X_num, X_cat, y = X_num.to(device), X_cat.to(device), y.to(device)\n",
        "\n",
        "        if mixup_alpha > 0:\n",
        "            X_num, X_cat, y, lam = mixup_data(X_num, X_cat, y, mixup_alpha)\n",
        "\n",
        "        if label_smoothing > 0:\n",
        "            y = y * (1.0 - label_smoothing) + 0.5 * label_smoothing\n",
        "\n",
        "        optimizer.zero_grad(set_to_none=True)\n",
        "\n",
        "        y_pred = model(X_num, X_cat).squeeze(-1)  # (batch, K)\n",
        "\n",
        "        # Average loss across independent ensemble members\n",
        "        y_pred_flat = y_pred.flatten()\n",
        "        y_flat = y.repeat_interleave(model.k)\n",
        "\n",
        "        loss = criterion(y_pred_flat, y_flat)\n",
        "        loss.backward()\n",
        "\n",
        "        if gradient_clipping_norm is not None:\n",
        "            torch.nn.utils.clip_grad_norm_(model.parameters(), gradient_clipping_norm)\n",
        "\n",
        "        optimizer.step()\n",
        "        total_loss += loss.item()\n",
        "\n",
        "    return total_loss / len(train_loader)\n",
