        "# ============================================\n",
        "# Pandas Feature Engineering (Stage 2: Ugly Duckling Features)\n",
        "# ============================================\n",
        "def add_ugly_duckling_features(df):\n",
        "    \"\"\"Add ugly-duckling z-score features to detect lesions unusual within location groups.\"\"\"\n",
        "    df = df.copy()\n",
        "    \n",
        "    # Find body location column\n",
        "    loc_col = None\n",
        "    for candidate in ['tbp_lv_location', 'tbp_lv_location_simple', 'anatom_site_general']:\n",
        "        if candidate in df.columns:\n",
        "            loc_col = candidate\n",
        "            break\n",
        "            \n",
        "    if loc_col is None:\n",
        "        return df\n",
        "        \n",
        "    source_cols = num_cols + new_num_cols\n",
        "    ud_loc_cols = []\n",
        "    ud_percentile_cols = []\n",
        "    \n",
        "    # Pre-compute groupby objects for performance\n",
        "    patient_grouped = df.groupby(group_col, observed=False, sort=False)\n",
        "    loc_grouped = df.groupby([group_col, loc_col], observed=False, sort=False)\n",
        "    \n",
        "    # Location-based z-scores and percentiles\n",
        "    for col in source_cols:\n",
        "        loc_mean = loc_grouped[col].transform('mean')\n",
        "        loc_std = loc_grouped[col].transform('std')\n",
        "        \n",
        "        new_col = f'ud_loc_{col}'\n",
        "        df[new_col] = (df[col] - loc_mean) / (loc_std + err)\n",
        "        ud_loc_cols.append(new_col)\n",
        "        \n",
        "        new_col_p = f'ud_percentile_{col}'\n",
        "        df[new_col_p] = patient_grouped[col].rank(pct=True)\n",
        "        ud_percentile_cols.append(new_col_p)\n",
        "        \n",
        "    # Aggregate statistics across location z-scores\n",
        "    ud_abs = df[ud_loc_cols].abs()\n",
        "    \n",
        "    df['ud_count_location'] = (ud_abs > 2.0).sum(axis=1)\n",
        "    df['ud_max_severity_location'] = ud_abs.max(axis=1)\n",
        "    df['ud_consistency_location'] = ud_abs.std(axis=1)\n",
        "    \n",
        "    return df\n",
        "\n",
        "print(\"Loading data and executing feature engineering...\")\n",
        "df_train = read_data(COMP_DATA_ROOT / 'train-metadata.csv')\n",
        "df_test = read_data(COMP_DATA_ROOT / 'test-metadata.csv')\n",
        "df_subm = pd.read_csv(COMP_DATA_ROOT / 'sample_submission.csv', index_col=id_col)\n",
        "\n",
        "# Process Ugly Duckling features\n",
        "df_train = add_ugly_duckling_features(df_train)\n",
